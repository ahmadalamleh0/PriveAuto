/**
 * Selected Projects for the VOIR-style collection gallery: Privé Auto's own
 * builds (client photography, 2026-11-12, from /Projects), Bugatti first.
 * 3:5 portrait crops at 560 and 960 wide (WebP + JPEG). Each card's photos
 * step through on tap; `video` on a photo plays a muted 3:5 loop over it
 * while it is the active slide. Maker marks are the brand logos from the
 * quote form (src/assets/brands), drawn as a mask in the text colour.
 *
 * Model names are only what the photos show; anything marked `confirm`
 * needs the client's check before launch.
 */

type Source = { url: string; w: number }
/** `video`: a muted 3:5 loop shown over this photo (its poster) while it is the active slide */
export type Photo = { alt: string; webp: Source[]; jpg: Source[]; position?: string; video?: string }
export type Project = {
  id: string
  make: string
  /** Shown vertically along the card's right edge */
  model: string
  /** Monochrome maker mark (SVG, drawn as a mask in the text colour). null → tracked wordmark of `make` */
  logo: string | null
  /** The still (for a video card, its poster: shown first, and instead of the video with reduced motion) */
  image: Photo | null
  /** Optional 3:5 muted loop (H.264, no audio): plays inline while the card is on screen */
  video?: string
  /** More photos after `image`, in order; the card shows dots and steps through them on tap */
  gallery?: Photo[]
  /** Model name not yet confirmed by the client */
  confirm?: string
}

const set = (pairs: [string, number][]) => pairs.map(([url, w]) => ({ url, w }))

